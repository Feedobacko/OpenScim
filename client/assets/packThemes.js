var nativeColorNames = ["orange", "orangeHover", "label", "body", "muted", "info"];
function nativeCssVariableName(c) {
  return "--native-" + c.replace(/[A-Z]/g, (d) => "-" + d.toLowerCase());
}
function applyPackTheme(d) {
  const f = packThemeColors[d] ?? packThemeColors["pack-browntown"];
  if ("undefined" != typeof document) {
    const documentElement2 = document.documentElement;
    for (const h of themeCssVariables) {
      documentElement2.style.setProperty("--" + h, f[h]);
    }
    for (const i of nativeColorNames) {
      documentElement2.style.setProperty(nativeCssVariableName(i), f.native[i]);
    }
    if (document.body) {
      document.body.style.background = f["color-surface-inset"];
    }
  }
  b(f);
}
